#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.join(root, "editor-approval-brief.md");
const readJSON = (name) => readFile(path.join(root, name), "utf8").then(JSON.parse);

function cell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

async function render() {
  const [catalog, contracts, matrix, interactions, world, approval] = await Promise.all([
    readJSON("chapter-catalog.json"),
    readJSON("chapter-contracts.json"),
    readJSON("arc-matrix.json"),
    readJSON("interaction-mapping.json"),
    readJSON("world-traces.json"),
    readJSON("editor-approval.json"),
  ]);
  const contractByID = new Map(contracts.contracts.map((item) => [item.contentID, item]));
  const matrixByID = new Map(matrix.chapters.map((item) => [item.contentID, item]));
  const interactionByID = new Map(interactions.items.map((item) => [item.nativeInteractionID, item]));
  const approvalLines = approval.status === "APPROVED_BY_EDITOR_IN_CHIEF"
    ? [
        `Approval status: \`${approval.status}\`  `,
        `Approved: ${approval.approvedAt}  `,
        `Decision reference: \`${approval.decisionReference}\``,
        "",
        "The editor-in-chief approved all 24 contracts and 55 arcs after selecting the four recommended resolutions recorded in `editor-review.md`. Those resolutions are applied in the authoritative contract files bound by `editor-approval.json`.",
      ]
    : [
        `Approval status: \`${approval.status}\``,
        "",
        "Four fields require an explicit choice before blanket approval: `first-farmers`, `bronze-europe`, `empire-takes-cross` and `empire-many-liberties`. Proposed resolutions remain in `editor-review.md`; none has been applied here.",
      ];
  const lines = [
    "# Phase 0 editor approval brief",
    "",
    "> Generated from the authoritative Phase 0 JSON. Do not edit this file by hand.",
    "> It is backstage production material and cannot enter a shipping package.",
    "",
    `Approval scope: ${catalog.chapters.length} chapter contracts, ${matrix.arcCount} native arcs, ${matrix.coveredMovementCount} source movements, ${interactions.counts.byRole.principal} principal interactions, ${interactions.counts.byRole.supporting} supporting source interactions and ${world.traces.length} cumulative world traces.`,
    "",
    ...approvalLines,
    "",
  ];

  for (const chapter of catalog.chapters) {
    const contract = contractByID.get(chapter.contentID);
    const chapterMatrix = matrixByID.get(chapter.contentID);
    lines.push(
      `## ${String(chapter.ordinal).padStart(2, "0")} — ${chapter.title}`,
      "",
      `ID: \`${chapter.contentID}\`  `,
      `Period: ${chapter.period}  `,
      `Access: ${chapter.freeAtLaunch ? "included in the base install" : "permanent collection purchase"}  `,
      `Approval: \`${contract.editorApproval}\``,
      "",
      "**Thesis**",
      "",
      contract.thesis,
      "",
      "**Europe-centred causal spine**",
      "",
      ...contract.causalSpine.map((item) => `- ${item}`),
      "",
      "**Required emphases**",
      "",
      ...contract.requiredEmphases.map((item) => `- ${item}`),
      "",
      "**Governing judgement**",
      "",
      contract.governingJudgement,
      "",
      "**Ending and handoff**",
      "",
      `${contract.ending.period} — ${contract.ending.title}`,
      "",
      contract.ending.consequence,
      "",
      `Handoff: ${contract.handoff}`,
      "",
      "**Native arc structure**",
      "",
      "| Arc | Target | Source movements | Mapped grammar / source prompt | Persistent traces |",
      "|---|---:|---:|---|---|",
    );
    for (const arc of chapterMatrix.arcs) {
      const grammars = arc.principalNativeInteractionIDs.map((id) => {
        const interaction = interactionByID.get(id);
        return `${interaction.nativeGrammar}: ${interaction.currentPrompt}`;
      });
      lines.push(`| ${cell(arc.title)} | ${arc.targetDurationMinutes} min | ${arc.movementIDs.length} | ${cell(grammars.join("; "))} | ${cell(arc.worldTraceIDs.join(", "))} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

async function main() {
  const expected = await render();
  if (process.argv.includes("--check")) {
    const actual = await readFile(outputPath, "utf8").catch(() => null);
    if (actual !== expected) throw new Error("editor-approval-brief.md is stale; regenerate it before review");
    process.stdout.write("Validated generated editor approval brief.\n");
    return;
  }
  await writeFile(outputPath, expected);
  process.stdout.write("Generated editor approval brief.\n");
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error.message}\n`);
  process.exitCode = 1;
});
